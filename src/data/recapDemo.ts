function withSlideMeta(slides: RecapSlide[]): RecapSlide[] {
	return slides
		.map((slide, index) => {
			const { triggerReason: _triggerReason, ...meta } = slideMeta[slide.id] ?? {};
			return {
				optional: true,
				priority: 1000 + index,
				emptyBehavior: 'hide',
				...meta,
				...slide,
			};
		});
}

